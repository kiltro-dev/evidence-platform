def iter_claims(piece_id):
    """Yield (slide, seg) claim segs (skips fillers) for one piece."""
    for slide in PIECES[piece_id]["slides"]:
        for seg in slide["segs"]:
            if "c" in seg:
                yield slide, seg


def narration_text(slide):
    """Spoken text for one slide: fillers + claim texts in order."""
    return " ".join(seg.get("f", seg.get("t", "")) for seg in slide["segs"])

